"""Users + JWT auth for the Clipper.

- Passwords are NEVER stored in plain text: bcrypt hash only.
- Sessions are JWT (HS256), 7 days, secret from JWT_SECRET env. On Render
  the secret is generated by the Blueprint (render.yaml). Locally, if
  JWT_SECRET is not set, a dev-only fallback is used and a warning is
  logged — do NOT rely on it in production.
- v1: /api/video-info, /api/clips, /api/render, /api/jobs, /api/download
  stay public. When a request carries a valid token, its user_id is
  recorded on the job (see main.py) so clips can later be listed per user.
"""
import logging
import os
from datetime import datetime, timedelta, timezone

import bcrypt
from fastapi import Depends, HTTPException, status
from fastapi.security import HTTPAuthorizationCredentials, HTTPBearer
from jose import JWTError, jwt
from sqlalchemy import Boolean, Column, DateTime, Integer, String
from sqlalchemy.orm import Session

from .db import Base, get_db

logger = logging.getLogger(__name__)

SECRET_KEY = os.environ.get("JWT_SECRET") or ""
if not SECRET_KEY:
    logger.warning(
        "JWT_SECRET not set — using dev-only fallback secret. "
        "Set JWT_SECRET in production (Render generates it).")
    SECRET_KEY = "clipper-dev-only-change-me"

ALGORITHM = "HS256"
ACCESS_TOKEN_EXPIRE_DAYS = 7

_bearer = HTTPBearer(auto_error=False)


class User(Base):
    __tablename__ = "users"

    id = Column(Integer, primary_key=True, index=True)
    name = Column(String(120), nullable=False)
    email = Column(String(255), unique=True, nullable=False, index=True)
    password_hash = Column(String(255), nullable=False)
    plan = Column(String(20), nullable=False, default="free")
    is_admin = Column(Boolean, nullable=False, default=False)
    # Mi Cuenta / Configuración: nombre que saldrá en el marco y su interruptor.
    brand_text = Column(String(120), nullable=False, default="@marketingcaribe")
    frame_enabled = Column(Boolean, nullable=False, default=True)
    created_at = Column(DateTime(timezone=True), nullable=False,
                        default=lambda: datetime.now(timezone.utc))


# Usuarios de prueba (seed). Las claves se guardan con bcrypt, como el
# resto. CÁMBIALAS después del primer inicio de sesión: en producción
# borra el seed o cambia estas claves en la base de datos.
SEED_USERS = [
    {"name": "Admin MarketingCaribe", "email": "admin@marketingcaribe.com",
     "password": "Admin1234!", "is_admin": True},
    {"name": "Usuario Demo", "email": "usuario@marketingcaribe.com",
     "password": "Usuario1234!", "is_admin": False},
]


def seed_users(db: Session) -> list[str]:
    """Create the demo users only when the users table is empty."""
    if db.query(User).count() > 0:
        return []
    created = []
    for seed in SEED_USERS:
        user = User(name=seed["name"], email=seed["email"],
                    password_hash=hash_password(seed["password"]),
                    is_admin=seed["is_admin"])
        db.add(user)
        created.append(seed["email"])
    db.commit()
    logger.info("Seed users created: %s", ", ".join(created))
    return created


def user_out(user: User) -> dict:
    return {
        "id": user.id,
        "name": user.name,
        "email": user.email,
        "plan": user.plan,
        "is_admin": bool(user.is_admin),
        "brand_text": user.brand_text,
        "frame_enabled": bool(user.frame_enabled),
        "created_at": user.created_at.isoformat() if user.created_at else None,
    }


def hash_password(password: str) -> str:
    if len(password.encode("utf-8")) > 72:
        raise ValueError("La contraseña no puede tener más de 72 caracteres")
    return bcrypt.hashpw(password.encode("utf-8"), bcrypt.gensalt()).decode("utf-8")


def verify_password(password: str, password_hash: str) -> bool:
    try:
        return bcrypt.checkpw(password.encode("utf-8"),
                              password_hash.encode("utf-8"))
    except (ValueError, TypeError):
        return False


def create_access_token(user_id: int) -> str:
    expire = datetime.now(timezone.utc) + timedelta(days=ACCESS_TOKEN_EXPIRE_DAYS)
    return jwt.encode({"sub": str(user_id), "exp": expire},
                      SECRET_KEY, algorithm=ALGORITHM)


def _user_id_from_token(token: str) -> int | None:
    try:
        payload = jwt.decode(token, SECRET_KEY, algorithms=[ALGORITHM])
        return int(payload.get("sub"))
    except (JWTError, ValueError, TypeError):
        return None


def register_user(db: Session, name: str, email: str, password: str) -> User:
    email = email.strip().lower()
    if not name.strip():
        raise ValueError("El nombre es obligatorio")
    if "@" not in email or "." not in email.split("@")[-1]:
        raise ValueError("Correo no válido")
    if len(password) < 6:
        raise ValueError("La contraseña debe tener al menos 6 caracteres")
    if db.query(User).filter(User.email == email).first():
        raise ValueError("Ese correo ya está registrado")
    user = User(name=name.strip(), email=email,
                password_hash=hash_password(password))
    db.add(user)
    db.commit()
    db.refresh(user)
    return user


def authenticate_user(db: Session, email: str, password: str) -> User | None:
    user = db.query(User).filter(User.email == email.strip().lower()).first()
    if user is None or not verify_password(password, user.password_hash):
        return None
    return user


def get_current_user(
    credentials: HTTPAuthorizationCredentials | None = Depends(_bearer),
    db: Session = Depends(get_db),
) -> User:
    """Require a valid token. 401 if missing/invalid."""
    user_id = _user_id_from_token(credentials.credentials) if credentials else None
    user = db.query(User).filter(User.id == user_id).first() if user_id else None
    if user is None:
        raise HTTPException(status_code=status.HTTP_401_UNAUTHORIZED,
                            detail="Inicia sesión para continuar")
    return user


def get_optional_user(
    credentials: HTTPAuthorizationCredentials | None = Depends(_bearer),
    db: Session = Depends(get_db),
) -> User | None:
    """v1 helper: return the user when a valid token is sent, else None.
    Never raises — public endpoints stay public."""
    user_id = _user_id_from_token(credentials.credentials) if credentials else None
    if not user_id:
        return None
    return db.query(User).filter(User.id == user_id).first()
