"""Users + JWT auth for the Clipper.

- Passwords are NEVER stored in plain text: bcrypt hash only.
- Sessions are JWT (HS256), 7 days, secret from JWT_SECRET env. On Render
  the secret is generated by the Blueprint (render.yaml). Locally, if
  JWT_SECRET is not set, a dev-only fallback is used and a warning is
  logged — do NOT rely on it in production.
- v1: /api/video-info, /api/clips, /api/render, /api/jobs, /api/download
  stay public. When a request carries a valid token, its user_id is
  recorded on the job (see main.py) so clips can later be listed per user.
"""
import logging
import os
import secrets
from datetime import datetime, timedelta, timezone

import bcrypt
from fastapi import Depends, HTTPException, Request, status
from fastapi.security import HTTPAuthorizationCredentials, HTTPBearer
from jose import JWTError, jwt
from sqlalchemy import Boolean, Column, DateTime, Float, Integer, String
from sqlalchemy.orm import Session

from .config import DEFAULT_BRAND_TEXT
from .db import Base, get_db

logger = logging.getLogger(__name__)

SECRET_KEY = os.environ.get("JWT_SECRET") or ""
if not SECRET_KEY:
    logger.warning(
        "JWT_SECRET not set — using dev-only fallback secret. "
        "Set JWT_SECRET in production (Render generates it).")
    SECRET_KEY = "clipper-dev-only-change-me"

ALGORITHM = "HS256"
ACCESS_TOKEN_EXPIRE_DAYS = 7

_bearer = HTTPBearer(auto_error=False)


class User(Base):
    __tablename__ = "users"

    id = Column(Integer, primary_key=True, index=True)
    name = Column(String(120), nullable=False)
    email = Column(String(255), unique=True, nullable=False, index=True)
    password_hash = Column(String(255), nullable=False)
    plan = Column(String(20), nullable=False, default="free")
    is_admin = Column(Boolean, nullable=False, default=False)
    # Suspendida por el admin (Panel Admin > Usuarios > Suspender):
    # no puede entrar ni usar el panel hasta que la reactiven.
    is_suspended = Column(Boolean, nullable=False, default=False)
    # Mi Cuenta / Configuración: nombre que saldrá en el marco y su interruptor.
    brand_text = Column(String(120), nullable=False, default="@marketingcaribe")
    frame_enabled = Column(Boolean, nullable=False, default=True)
    # Preferencias de clips (Configuración > Crear Clip): se guardan con
    # PATCH /api/auth/me y se usan como valores por defecto al generar.
    max_clips = Column(Integer, nullable=False, default=5)
    min_clip_secs = Column(Float, nullable=False, default=20.0)
    max_clip_secs = Column(Float, nullable=False, default=45.0)
    quality = Column(String(10), nullable=False, default="1080p")  # 720p | 1080p
    subtitles_enabled = Column(Boolean, nullable=False, default=True)
    template = Column(String(80), nullable=False, default="Gancho grande")
    created_at = Column(DateTime(timezone=True), nullable=False,
                        default=lambda: datetime.now(timezone.utc))
    # Sesión única (2026-11-13, Juan: una sola sesión activa por cuenta,
    # atada a una IP y un dispositivo): cada login genera un session_id
    # nuevo e invalida el anterior; el token lleva el session_id y la IP.
    active_session_id = Column(String(64), nullable=True)
    active_session_ip = Column(String(45), nullable=True)
    active_session_agent = Column(String(255), nullable=True)
    active_session_at = Column(DateTime(timezone=True), nullable=True)


# Usuarios de prueba (seed). Las claves se guardan con bcrypt, como el
# resto. CÁMBIALAS después del primer inicio de sesión: en producción
# borra el seed o cambia estas claves en la base de datos.
SEED_USERS = [
    {"name": "Admin MarketingCaribe", "email": "admin@marketingcaribe.com",
     "password": "Admin1234!", "is_admin": True},
    {"name": "Usuario Demo", "email": "usuario@marketingcaribe.com",
     "password": "Usuario1234!", "is_admin": False},
]


def _apply_platform_defaults(db: Session, user: User) -> None:
    """New users get the admin's platform defaults (brand + frame)."""
    try:
        from .settings import get_setting
        brand = get_setting(db, "default_brand_text", DEFAULT_BRAND_TEXT)
        frame = get_setting(db, "default_frame_enabled", "true")
        tpl = get_setting(db, "default_template", "Gancho grande")
        user.brand_text = brand or DEFAULT_BRAND_TEXT
        user.frame_enabled = str(frame).lower() not in ("false", "0", "no")
        user.template = (tpl or "Gancho grande").strip()[:80] or "Gancho grande"
    except Exception:  # noqa: BLE001 — defaults are best-effort
        pass


def seed_users(db: Session) -> list[str]:
    """Create the demo users only when the users table is empty."""
    if db.query(User).count() > 0:
        return []
    created = []
    for seed in SEED_USERS:
        user = User(name=seed["name"], email=seed["email"],
                    password_hash=hash_password(seed["password"]),
                    is_admin=seed["is_admin"])
        _apply_platform_defaults(db, user)
        db.add(user)
        created.append(seed["email"])
    db.commit()
    logger.info("Seed users created: %s", ", ".join(created))
    return created


def user_out(user: User) -> dict:
    return {
        "id": user.id,
        "name": user.name,
        "email": user.email,
        "plan": user.plan,
        "is_admin": bool(user.is_admin),
        "is_suspended": bool(getattr(user, "is_suspended", False)),
        "brand_text": user.brand_text,
        "frame_enabled": bool(user.frame_enabled),
        "max_clips": user.max_clips if user.max_clips is not None else 5,
        "min_clip_secs": user.min_clip_secs if user.min_clip_secs is not None else 20.0,
        "max_clip_secs": user.max_clip_secs if user.max_clip_secs is not None else 45.0,
        "quality": user.quality or "1080p",
        "subtitles_enabled": bool(user.subtitles_enabled) if user.subtitles_enabled is not None else True,
        "template": user.template or "Gancho grande",
        "created_at": user.created_at.isoformat() if user.created_at else None,
    }


def hash_password(password: str) -> str:
    if len(password.encode("utf-8")) > 72:
        raise ValueError("La contraseña no puede tener más de 72 caracteres")
    return bcrypt.hashpw(password.encode("utf-8"), bcrypt.gensalt()).decode("utf-8")


def verify_password(password: str, password_hash: str) -> bool:
    try:
        return bcrypt.checkpw(password.encode("utf-8"),
                              password_hash.encode("utf-8"))
    except (ValueError, TypeError):
        return False


def create_access_token(user_id: int, session_id: str | None = None) -> str:
    expire = datetime.now(timezone.utc) + timedelta(days=ACCESS_TOKEN_EXPIRE_DAYS)
    payload: dict = {"sub": str(user_id), "exp": expire}
    if session_id:
        payload["sid"] = session_id
    return jwt.encode(payload, SECRET_KEY, algorithm=ALGORITHM)


def _token_payload(token: str) -> tuple[int | None, str | None]:
    """Decodifica el JWT: (user_id, session_id). Sin sid = token viejo."""
    try:
        payload = jwt.decode(token, SECRET_KEY, algorithms=[ALGORITHM])
        return int(payload.get("sub")), payload.get("sid")
    except (JWTError, ValueError, TypeError):
        return None, None


def _user_id_from_token(token: str) -> int | None:
    user_id, _sid = _token_payload(token)
    return user_id


def start_session(db: Session, user: User, ip: str | None,
                  agent: str | None) -> str:
    """Crea la sesión única: invalida cualquier sesión anterior de la
    cuenta (el token viejo deja de valer en la próxima petición)."""
    sid = secrets.token_urlsafe(32)
    user.active_session_id = sid
    user.active_session_ip = ip
    user.active_session_agent = (agent or "")[:255] or None
    user.active_session_at = datetime.now(timezone.utc)
    db.add(user)
    db.commit()
    return sid


def end_session(db: Session, user: User) -> None:
    """Cierra la sesión: el token vigente deja de valer."""
    user.active_session_id = None
    user.active_session_ip = None
    user.active_session_agent = None
    user.active_session_at = None
    db.add(user)
    db.commit()


def register_user(db: Session, name: str, email: str, password: str) -> User:
    email = email.strip().lower()
    if not name.strip():
        raise ValueError("El nombre es obligatorio")
    if "@" not in email or "." not in email.split("@")[-1]:
        raise ValueError("Correo no válido")
    if len(password) < 6:
        raise ValueError("La contraseña debe tener al menos 6 caracteres")
    if db.query(User).filter(User.email == email).first():
        raise ValueError("Ese correo ya está registrado")
    user = User(name=name.strip(), email=email,
                password_hash=hash_password(password))
    _apply_platform_defaults(db, user)
    db.add(user)
    db.commit()
    db.refresh(user)
    return user


def authenticate_user(db: Session, email: str, password: str) -> User | None:
    user = db.query(User).filter(User.email == email.strip().lower()).first()
    if user is None or not verify_password(password, user.password_hash):
        return None
    return user


def get_current_user(
    request: Request,
    credentials: HTTPAuthorizationCredentials | None = Depends(_bearer),
    db: Session = Depends(get_db),
) -> User:
    """Require a valid token. 401 if missing/invalid. A suspended
    account (is_suspended, set by the admin) gets 403 on every call
    except for admins themselves, so it cannot use the panel until
    reactivated. Sesión única (v111): el token debe llevar el
    session_id vigente; si la cuenta inició sesión en otro dispositivo,
    este token ya no vale. La IP se registra en el login solo como
    auditoría (no se exige: la IP real cambia sola entre peticiones)."""
    user_id, sid = _token_payload(credentials.credentials) if credentials else (None, None)
    user = db.query(User).filter(User.id == user_id).first() if user_id else None
    if user is None:
        raise HTTPException(status_code=status.HTTP_401_UNAUTHORIZED,
                            detail="Inicia sesión para continuar")
    active = getattr(user, "active_session_id", None)
    if sid is None:
        # Token viejo sin sid: solo vale si el usuario nunca inició sesión
        # con la sesión única (v111+). Si ya tiene sesión vigente, el
        # token viejo quedó invalidado por el login nuevo.
        if active is not None:
            raise HTTPException(status_code=status.HTTP_401_UNAUTHORIZED,
                                detail="Tu sesión se cerró porque iniciaste "
                                "sesión en otro dispositivo")
    elif sid != active:
        # Token con sid que no coincide: otro login lo invalidó, o se
        # cerró la sesión (logout deja active en None).
        raise HTTPException(status_code=status.HTTP_401_UNAUTHORIZED,
                            detail="Tu sesión se cerró porque iniciaste "
                            "sesión en otro dispositivo")
    if getattr(user, "is_suspended", False) and not user.is_admin:
        raise HTTPException(status_code=status.HTTP_403_FORBIDDEN,
                            detail="Tu cuenta está suspendida. "
                            "Contacta al administrador.")
    return user


def get_optional_user(
    credentials: HTTPAuthorizationCredentials | None = Depends(_bearer),
    db: Session = Depends(get_db),
) -> User | None:
    """v1 helper: return the user when a valid token is sent, else None.
    Never raises — public endpoints stay public."""
    user_id, sid = _token_payload(credentials.credentials) if credentials else (None, None)
    if not user_id:
        return None
    user = db.query(User).filter(User.id == user_id).first()
    if user is None:
        return None
    active = getattr(user, "active_session_id", None)
    if active is not None and sid != active:
        return None
    return user
